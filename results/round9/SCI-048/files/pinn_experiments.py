def plot_adaptive_collocation_demo():
    """Visualize adaptive collocation point redistribution."""
    print("\n=== Adaptive Collocation Visualization ===")
    torch.manual_seed(SEED)
    np.random.seed(SEED)

    # Train a simple Fourier PINN briefly to get residuals
    model = FourierPINN(2, 1, 64, 4, 64, 5.0).to(DEVICE)
    optimizer = optim.Adam(model.parameters(), lr=1e-3)
    xt_col, _, _, xt_ic, u_ic = generate_burgers_data(n_colloc=3000)
    xt_col_t = torch.tensor(xt_col, dtype=torch.float32, device=DEVICE)

    # Train briefly (500 epochs)
    for epoch in range(500):
        model.train()
        optimizer.zero_grad()
        xt_ic_t = torch.tensor(xt_ic, dtype=torch.float32, device=DEVICE)
        u_ic_t = torch.tensor(u_ic, dtype=torch.float32, device=DEVICE)
        u_pred_ic = model(xt_ic_t)
        loss_ic = torch.mean((u_pred_ic - u_ic_t)**2)
        res = burgers_residual(model, xt_col_t.clone())
        loss_pde = torch.mean(res**2)
        loss = loss_ic + loss_pde
        loss.backward()
        optimizer.step()

    # Compute residuals — must use enable_grad context
    model.train()
    with torch.enable_grad():
        xt_col_grad = xt_col_t.clone().requires_grad_(True)
        res_vals = burgers_residual(model, xt_col_grad).abs().squeeze().detach().cpu().numpy()

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    ax = axes[0]
    sc = ax.scatter(xt_col[:, 0], xt_col[:, 1], c=res_vals, cmap='hot_r',
                    s=5, alpha=0.7, vmin=0, vmax=np.percentile(res_vals, 95))
    plt.colorbar(sc, ax=ax, label='|Residual|')
    ax.set_xlabel('x', fontsize=13); ax.set_ylabel('t', fontsize=13)
    ax.set_title('Uniform Collocation (residual magnitude)', fontsize=13)

    # Resample adaptively
    probs = res_vals / res_vals.sum()
    idx = np.random.choice(len(probs), size=len(probs), replace=True, p=probs)
    xt_adaptive = xt_col[idx]

    ax = axes[1]
    ax.scatter(xt_adaptive[:, 0], xt_adaptive[:, 1], c='steelblue', s=5, alpha=0.5)
    ax.set_xlabel('x', fontsize=13); ax.set_ylabel('t', fontsize=13)
    ax.set_title('Adaptive Collocation (residual-based redistribution)', fontsize=13)

    plt.tight_layout()
    path = os.path.join(FIG_DIR, 'fig06_adaptive_collocation.png')
    plt.savefig(path, dpi=150, bbox_inches='tight')
    plt.close()
    print(f"  Saved: {path}")


