def evaluate_burgers(model, n_eval=50):
    """Evaluate PINN on grid, L2 relative error vs FD reference."""
    from scipy.interpolate import RegularGridInterpolator
    x_eval = np.linspace(-1, 1, n_eval)
    t_eval = np.linspace(0, 1, n_eval)
    XX, TT = np.meshgrid(x_eval, t_eval)
    xt_eval = np.column_stack([XX.ravel(), TT.ravel()])
    xt_t = torch.tensor(xt_eval, dtype=torch.float32, device=DEVICE)

    model.eval()
    with torch.no_grad():
        u_pred = model(xt_t).cpu().numpy().reshape(n_eval, n_eval)

    interp = RegularGridInterpolator((FD_T, FD_X), FD_U, method='linear',
                                      bounds_error=False, fill_value=None)
    pts = np.column_stack([TT.ravel(), XX.ravel()])
    u_ref = interp(pts).reshape(n_eval, n_eval)

    l2_err = np.linalg.norm(u_pred - u_ref) / (np.linalg.norm(u_ref) + 1e-10)
    return l2_err, u_pred, u_ref, x_eval, t_eval


