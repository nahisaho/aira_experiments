# MODULE 5: Navier-Stokes (2D Kovasznay flow)
# Steady-state laminar flow: exact Kovasznay solution
# ============================================================

RE = 40.0  # Reynolds number

def kovasznay_exact(x, y):
    """Kovasznay flow exact solution (Re=40)."""
    lam = RE/2 - np.sqrt(RE**2/4 + 4*np.pi**2)
    u = 1 - np.exp(lam * x) * np.cos(2*np.pi*y)
    v = lam / (2*np.pi) * np.exp(lam * x) * np.sin(2*np.pi*y)
    p = 0.5*(1 - np.exp(2*lam*x))
    return u, v, p


class NavierStokesPINN(nn.Module):
    """PINN for 2D steady Navier-Stokes (Kovasznay flow)."""
    def __init__(self, hidden=64, layers=6, num_fourier=64, sigma=3.0):
        super().__init__()
        in_dim = 2
        B = torch.randn(in_dim, num_fourier) * sigma
        self.register_buffer('B', B)
        fourier_out = num_fourier * 2
        # Output: [u, v, p]
        net = [nn.Linear(fourier_out, hidden), nn.Tanh()]
        for _ in range(layers - 2):
            net += [nn.Linear(hidden, hidden), nn.Tanh()]
        net += [nn.Linear(hidden, 3)]
        self.net = nn.Sequential(*net)
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_normal_(m.weight)
                nn.init.zeros_(m.bias)

    def fourier_embed(self, x):
        proj = 2 * np.pi * x @ self.B
        return torch.cat([torch.sin(proj), torch.cos(proj)], dim=-1)

    def forward(self, xy):
        return self.net(self.fourier_embed(xy))

    def ns_residuals(self, xy):
        xy = xy.clone().requires_grad_(True)
        out = self.forward(xy)
        u, v, p = out[:, 0:1], out[:, 1:2], out[:, 2:3]

        def grad1(y, x):
            return torch.autograd.grad(y.sum(), x, create_graph=True)[0]

        du = grad1(u, xy)
        dv = grad1(v, xy)
        dp = grad1(p, xy)

        u_x, u_y = du[:, 0:1], du[:, 1:2]
        v_x, v_y = dv[:, 0:1], dv[:, 1:2]
        p_x, p_y = dp[:, 0:1], dp[:, 1:2]

        u_xx = grad1(u_x, xy)[:, 0:1]
        u_yy = grad1(u_y, xy)[:, 1:2]
        v_xx = grad1(v_x, xy)[:, 0:1]
        v_yy = grad1(v_y, xy)[:, 1:2]

        nu = 1.0 / RE
        # Momentum x: u*u_x + v*u_y + p_x - nu*(u_xx+u_yy) = 0
        # Momentum y: u*v_x + v*v_y + p_y - nu*(v_xx+v_yy) = 0
        # Continuity: u_x + v_y = 0
        res_x = u * u_x + v * u_y + p_x - nu * (u_xx + u_yy)
        res_y = u * v_x + v * v_y + p_y - nu * (v_xx + v_yy)
        res_c = u_x + v_y
        return res_x, res_y, res_c


def train_ns_pinn():
    """Train Navier-Stokes PINN on Kovasznay flow."""
    print("\n=== Experiment 2: Navier-Stokes (Kovasznay Flow, Re=40) ===")
    torch.manual_seed(SEED)
