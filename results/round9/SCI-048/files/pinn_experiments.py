class InversePINN(nn.Module):
    """PINN with learnable PDE parameter (nu)."""
    def __init__(self, nu_init=0.005):
        super().__init__()
        self.nu_log = nn.Parameter(torch.log(torch.tensor(nu_init)))
        # Fourier PINN backbone
        in_dim, hidden, layers, num_fourier, sigma = 2, 64, 5, 64, 5.0
        B = torch.randn(in_dim, num_fourier) * sigma
        self.register_buffer('B', B)
        fourier_out = num_fourier * 2
        net = [nn.Linear(fourier_out, hidden), nn.Tanh()]
        for _ in range(layers - 2):
            net += [nn.Linear(hidden, hidden), nn.Tanh()]
        net += [nn.Linear(hidden, 1)]
        self.net = nn.Sequential(*net)
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_normal_(m.weight)
                nn.init.zeros_(m.bias)

    @property
    def nu(self):
        return torch.exp(self.nu_log)

    def fourier_embed(self, x):
        proj = 2 * np.pi * x @ self.B
        return torch.cat([torch.sin(proj), torch.cos(proj)], dim=-1)

    def forward(self, x):
        return self.net(self.fourier_embed(x))

    def residual(self, xt):
        xt = xt.clone().requires_grad_(True)
        u = self.forward(xt)
        grads = torch.autograd.grad(u.sum(), xt, create_graph=True)[0]
        u_t = grads[:, 1:2]
        u_x = grads[:, 0:1]
        u_xx = torch.autograd.grad(u_x.sum(), xt, create_graph=True)[0][:, 0:1]
        return u_t + u * u_x - self.nu * u_xx


