# MODULE 2: Burgers Equation (1D + time)
# u_t + u*u_x = nu * u_xx
# Exact: viscous Burgers with nu=0.01/pi
# ============================================================

NU_TRUE = 0.01 / np.pi

def burgers_exact(x, t, nu=NU_TRUE):
    """Exact solution via Hopf-Cole transform (simplified)."""
    # Standard traveling wave approximation for nu=0.01/pi
    return -np.tanh((x + 0.5*t) / (2*nu)) + 0.0

def burgers_residual(model, xt):
    """Compute Burgers PDE residual."""
    xt.requires_grad_(True)
    u = model(xt)
    grads = torch.autograd.grad(u.sum(), xt, create_graph=True)[0]
    u_t = grads[:, 1:2]
    u_x = grads[:, 0:1]
    u_xx = torch.autograd.grad(u_x.sum(), xt, create_graph=True)[0][:, 0:1]
    residual = u_t + u * u_x - NU_TRUE * u_xx
    return residual


def generate_burgers_data(n_colloc=2000, n_bc=200, n_ic=200, noise_std=0.0):
    """Generate training data for Burgers equation on [-1,1] x [0,1]."""
    np.random.seed(SEED)
    # Collocation points (interior)
    x_col = np.random.uniform(-1, 1, (n_colloc, 1))
    t_col = np.random.uniform(0, 1, (n_colloc, 1))
    xt_col = np.hstack([x_col, t_col])

    # Boundary conditions: u(-1,t) = u(1,t) = 0 (Dirichlet)
    t_bc = np.random.uniform(0, 1, (n_bc, 1))
    x_left = np.full_like(t_bc, -1.0)
    x_right = np.full_like(t_bc, 1.0)
    xt_bc_left = np.hstack([x_left, t_bc])
    xt_bc_right = np.hstack([x_right, t_bc])

    # Initial condition: u(x,0) = -sin(pi*x)
    x_ic = np.linspace(-1, 1, n_ic).reshape(-1, 1)
    t_ic = np.zeros_like(x_ic)
    xt_ic = np.hstack([x_ic, t_ic])
    u_ic = -np.sin(np.pi * x_ic)

    return (xt_col, xt_bc_left, xt_bc_right, xt_ic, u_ic)


def train_pinn_burgers(model, n_epochs=5000, lr=1e-3, use_causal=False,
                       causal_eps=1.0, adaptive_colloc=False,
                       verbose=True, label='PINN'):
    """Train PINN on 1D Burgers equation."""
    torch.manual_seed(SEED)
    np.random.seed(SEED)

    xt_col, xt_bc_l, xt_bc_r, xt_ic, u_ic = generate_burgers_data(
        n_colloc=1000, n_bc=100, n_ic=100)

    def to_tensor(arr):
        return torch.tensor(arr, dtype=torch.float32, device=DEVICE)

    xt_col_t = to_tensor(xt_col)
    xt_bc_l_t = to_tensor(xt_bc_l)
    xt_bc_r_t = to_tensor(xt_bc_r)
    xt_ic_t = to_tensor(xt_ic)
    u_ic_t = to_tensor(u_ic)

    optimizer = optim.Adam(model.parameters(), lr=lr)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=n_epochs)

    loss_history = []
    start = time.time()

    # Time stamps for causal training
    if use_causal:
        T_vals = torch.unique(torch.linspace(0, 1, 20, device=DEVICE))

    for epoch in range(n_epochs):
        model.train()
        optimizer.zero_grad()

        # IC loss
        u_pred_ic = model(xt_ic_t)
        loss_ic = torch.mean((u_pred_ic - u_ic_t) ** 2)

        # BC loss
        u_pred_bc_l = model(xt_bc_l_t)
        u_pred_bc_r = model(xt_bc_r_t)
        loss_bc = torch.mean(u_pred_bc_l ** 2) + torch.mean(u_pred_bc_r ** 2)

        # PDE residual
        if use_causal:
            # Causal training: weight residuals by cumulative temporal error
            res = burgers_residual(model, xt_col_t.clone())
            t_col_vals = xt_col_t[:, 1]
            # Compute causal weights: w_k = exp(-eps * sum_{j<k} L_j)
            t_bins = torch.linspace(0, 1, 11, device=DEVICE)
            loss_pde_vals = []
            causal_weights = []
            cum_loss = 0.0
            for i in range(len(t_bins) - 1):
                mask = (t_col_vals >= t_bins[i]) & (t_col_vals < t_bins[i + 1])
                if mask.sum() > 0:
                    l = torch.mean(res[mask] ** 2)
                    w = torch.exp(torch.tensor(-causal_eps * cum_loss, device=DEVICE))
                    loss_pde_vals.append(w * l)
                    cum_loss = cum_loss + l.item()
            loss_pde = sum(loss_pde_vals) / len(loss_pde_vals) if loss_pde_vals else torch.tensor(0.0)
        else:
            res = burgers_residual(model, xt_col_t.clone())
            loss_pde = torch.mean(res ** 2)

        loss = loss_ic + loss_bc + loss_pde
        loss.backward()
        optimizer.step()
        scheduler.step()

        if adaptive_colloc and (epoch + 1) % 500 == 0:
            # Adaptive collocation: resample with probability proportional to |residual|
            # Must use enable_grad since burgers_residual needs autograd
            with torch.enable_grad():
                res_val = burgers_residual(model, xt_col_t.clone()).abs().squeeze().detach()
            probs = (res_val / res_val.sum()).cpu().numpy()
            idx = np.random.choice(len(probs), size=len(probs), replace=True, p=probs)
            xt_col_t = xt_col_t[idx].detach()

        loss_history.append(loss.item())

    elapsed = time.time() - start
    if verbose:
        print(f"  [{label}] Final loss: {loss_history[-1]:.6f}, Time: {elapsed:.1f}s")

    return loss_history, elapsed


def burgers_fd_reference(n_x=256):
    """Stable FD reference for Burgers using conservative upwind + Euler.
    Returns solution on a uniform time grid t in [0,1].
    """
    dx = 2.0 / (n_x - 1)
    dt = 0.3 * dx  # CFL-safe for |u| <= 1
    x = np.linspace(-1, 1, n_x)
    u = -np.sin(np.pi * x).copy()
    nu = NU_TRUE
    t = 0.0
    T_end = 1.0

    # Store at uniform t grid
    n_store = 101
    t_store = np.linspace(0, T_end, n_store)
    U_store = np.zeros((n_store, n_x))
    U_store[0] = u.copy()
    store_idx = 1

    while t < T_end - 1e-12:
        dt_actual = min(dt, T_end - t, t_store[store_idx] - t + 1e-12 if store_idx < n_store else 1.0)
        # Godunov upwind for u^2/2
        u_plus = np.maximum(u, 0)
        u_minus = np.minimum(u, 0)
        flux_right = 0.5 * u_plus[:-1]**2 + 0.5 * u_minus[1:]**2
        adv = np.zeros(n_x)
        adv[1:-1] = -(flux_right[1:] - flux_right[:-1]) / dx
        # Diffusion central
        u_xx = np.zeros(n_x)
        u_xx[1:-1] = (u[2:] - 2*u[1:-1] + u[:-2]) / dx**2
        u_new = u + dt_actual * (adv + nu * u_xx)
        u_new[0] = 0.0; u_new[-1] = 0.0
        u = u_new
        t += dt_actual
        # Store if we reached a storage checkpoint
        while store_idx < n_store and t >= t_store[store_idx] - 1e-10:
            U_store[store_idx] = u.copy()
            store_idx += 1

    return x, t_store, U_store


