class StandardPINN(nn.Module):
    """Vanilla MLP PINN (baseline)."""
    def __init__(self, in_dim=2, out_dim=1, hidden=64, layers=5):
        super().__init__()
        net = [nn.Linear(in_dim, hidden), nn.Tanh()]
        for _ in range(layers - 2):
            net += [nn.Linear(hidden, hidden), nn.Tanh()]
        net += [nn.Linear(hidden, out_dim)]
        self.net = nn.Sequential(*net)
        self._init_weights()

    def _init_weights(self):
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_normal_(m.weight)
                nn.init.zeros_(m.bias)

    def forward(self, x):
        return self.net(x)


class FourierPINN(nn.Module):
    """PINN with Random Fourier Feature embedding (Tancik et al., 2020)."""
    def __init__(self, in_dim=2, out_dim=1, hidden=64, layers=5,
                 num_fourier=128, sigma=10.0):
        super().__init__()
        # Fourier embedding: fixed random projection
        B = torch.randn(in_dim, num_fourier) * sigma
        self.register_buffer('B', B)
        fourier_out = num_fourier * 2  # sin + cos
        net = [nn.Linear(fourier_out, hidden), nn.Tanh()]
        for _ in range(layers - 2):
            net += [nn.Linear(hidden, hidden), nn.Tanh()]
        net += [nn.Linear(hidden, out_dim)]
        self.net = nn.Sequential(*net)
        self._init_weights()

    def _init_weights(self):
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_normal_(m.weight)
                nn.init.zeros_(m.bias)

    def fourier_embed(self, x):
        proj = 2 * np.pi * x @ self.B
        return torch.cat([torch.sin(proj), torch.cos(proj)], dim=-1)

    def forward(self, x):
        return self.net(self.fourier_embed(x))


class MCDropoutPINN(nn.Module):
    """PINN with MC Dropout for uncertainty quantification."""
    def __init__(self, in_dim=2, out_dim=1, hidden=64, layers=5,
                 dropout_rate=0.1, num_fourier=64, sigma=5.0):
        super().__init__()
        B = torch.randn(in_dim, num_fourier) * sigma
        self.register_buffer('B', B)
        fourier_out = num_fourier * 2
        self.dropout = nn.Dropout(p=dropout_rate)
        net = [nn.Linear(fourier_out, hidden), nn.Tanh(), self.dropout]
        for _ in range(layers - 2):
            net += [nn.Linear(hidden, hidden), nn.Tanh(), self.dropout]
        net += [nn.Linear(hidden, out_dim)]
        self.net = nn.Sequential(*net)
        self._init_weights()

    def _init_weights(self):
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_normal_(m.weight)
                nn.init.zeros_(m.bias)

    def fourier_embed(self, x):
        proj = 2 * np.pi * x @ self.B
        return torch.cat([torch.sin(proj), torch.cos(proj)], dim=-1)

    def forward(self, x):
        return self.net(self.fourier_embed(x))

    def predict_with_uncertainty(self, x, n_samples=50):
        """MC Dropout inference: keep dropout active during prediction."""
        self.train()
        preds = torch.stack([self.forward(x) for _ in range(n_samples)], dim=0)
        mean = preds.mean(0)
        std = preds.std(0)
        return mean, std


