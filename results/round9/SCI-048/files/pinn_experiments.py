def run_uq_experiment():
    """Run MC Dropout uncertainty quantification on 1D Burgers."""
    print("\n=== Experiment 3: Uncertainty Quantification (MC Dropout) ===")
    torch.manual_seed(SEED)
    np.random.seed(SEED)

    xt_col, xt_bc_l, xt_bc_r, xt_ic, u_ic = generate_burgers_data(
        n_colloc=1000, n_bc=100, n_ic=100, noise_std=0.02)

    def to_t(a): return torch.tensor(a, dtype=torch.float32, device=DEVICE)

    xt_col_t = to_t(xt_col)
    xt_bc_l_t = to_t(xt_bc_l)
    xt_bc_r_t = to_t(xt_bc_r)
    xt_ic_t = to_t(xt_ic)
    u_ic_t = to_t(u_ic)

    # Add noise to IC for UQ
    u_ic_noisy = u_ic + np.random.normal(0, 0.02, u_ic.shape)
    u_ic_noisy_t = to_t(u_ic_noisy)

    model = MCDropoutPINN(2, 1, 64, 5, dropout_rate=0.05, num_fourier=64, sigma=5.0).to(DEVICE)
    optimizer = optim.Adam(model.parameters(), lr=1e-3)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=5000)

    loss_history = []
    for epoch in range(3000):
        model.train()
        optimizer.zero_grad()
        u_pred_ic = model(xt_ic_t)
        loss_ic = torch.mean((u_pred_ic - u_ic_noisy_t) ** 2)
        u_pred_bc_l = model(xt_bc_l_t)
        u_pred_bc_r = model(xt_bc_r_t)
        loss_bc = torch.mean(u_pred_bc_l**2) + torch.mean(u_pred_bc_r**2)
        # PDE
        xt_col_c = xt_col_t.clone().requires_grad_(True)
        u_c = model(xt_col_c)
        grads = torch.autograd.grad(u_c.sum(), xt_col_c, create_graph=True)[0]
        u_t = grads[:, 1:2]
        u_x = grads[:, 0:1]
        u_xx = torch.autograd.grad(u_x.sum(), xt_col_c, create_graph=True)[0][:, 0:1]
        res = u_t + u_c * u_x - NU_TRUE * u_xx
        loss_pde = torch.mean(res ** 2)
        loss = loss_ic + loss_bc + loss_pde
        loss.backward()
        optimizer.step()
        scheduler.step()
        loss_history.append(loss.item())

    # Evaluate with UQ on t=0.5 slice
    x_test = np.linspace(-1, 1, 100).reshape(-1, 1)
    t_test = np.full_like(x_test, 0.5)
    xt_test = np.hstack([x_test, t_test])
    xt_test_t = to_t(xt_test)

    mean, std = model.predict_with_uncertainty(xt_test_t, n_samples=100)
    mean_np = mean.detach().cpu().numpy().squeeze()
    std_np = std.detach().cpu().numpy().squeeze()

    u_exact = -np.sin(np.pi * x_test.squeeze()) * np.exp(-NU_TRUE * np.pi**2 * 0.5)
    l2_uq = np.linalg.norm(mean_np - u_exact) / (np.linalg.norm(u_exact) + 1e-10)
    coverage_95 = np.mean(np.abs(mean_np - u_exact) <= 1.96 * std_np)
    print(f"  L2 error (mean prediction): {l2_uq:.4f}")
    print(f"  95% CI coverage: {coverage_95:.4f}")

    results['uq_l2_error'] = l2_uq
    results['uq_coverage_95'] = coverage_95
    results['uq_mean_std'] = float(std_np.mean())

    return x_test.squeeze(), mean_np, std_np, u_exact, loss_history


