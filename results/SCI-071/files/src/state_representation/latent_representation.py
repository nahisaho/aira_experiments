"""Learned latent state representation for deformable objects."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping

import numpy as np
import torch
from torch import Tensor, nn
from torch.nn import functional as F


def _ensure_tensor(value: Any, *, name: str, device: torch.device | None = None) -> Tensor:
    tensor = value if isinstance(value, Tensor) else torch.as_tensor(value)
    if tensor.ndim == 0:
        raise ValueError(f"{name} must not be scalar.")
    tensor = tensor.to(device=device, dtype=torch.float32)
    return tensor


@dataclass(slots=True)
class LatentState:
    """Structured latent representation generated by a VAE."""

    latent: Tensor
    mean: Tensor
    logvar: Tensor
    num_points: tuple[int, ...]
    input_dim: int
    batched: bool
    mask: Tensor | None = None

    def __post_init__(self) -> None:
        if self.latent.ndim != 2:
            raise ValueError(f"latent must have shape (B, D), got {tuple(self.latent.shape)}.")
        if self.mean.shape != self.latent.shape or self.logvar.shape != self.latent.shape:
            raise ValueError("mean and logvar must match latent shape.")
        if len(self.num_points) != self.latent.shape[0]:
            raise ValueError("num_points must contain one entry per batch element.")
        if self.mask is not None and self.mask.shape[0] != self.latent.shape[0]:
            raise ValueError("mask batch dimension must match latent batch dimension.")

    def __repr__(self) -> str:
        return (
            "LatentState("
            f"latent={tuple(self.latent.shape)}, "
            f"num_points={self.num_points}, "
            f"input_dim={self.input_dim}, "
            f"batched={self.batched})"
        )


class LatentRepresentation(nn.Module):
    """Variational autoencoder for point-cloud deformable states."""

    def __init__(
        self,
        *,
        input_dim: int = 3,
        latent_dim: int = 64,
        hidden_dim: int = 128,
        max_points: int = 256,
        beta: float = 1.0,
    ) -> None:
        super().__init__()
        if input_dim <= 0:
            raise ValueError("input_dim must be positive.")
        if latent_dim <= 0:
            raise ValueError("latent_dim must be positive.")
        if hidden_dim <= 0:
            raise ValueError("hidden_dim must be positive.")
        if max_points <= 0:
            raise ValueError("max_points must be positive.")
        if beta <= 0.0:
            raise ValueError("beta must be positive.")

        self.input_dim = input_dim
        self.latent_dim = latent_dim
        self.hidden_dim = hidden_dim
        self.max_points = max_points
        self.beta = beta

        self.point_encoder = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, hidden_dim),
            nn.GELU(),
        )
        self.mean_head = nn.Linear(hidden_dim, latent_dim)
        self.logvar_head = nn.Linear(hidden_dim, latent_dim)
        self.decoder = nn.Sequential(
            nn.Linear(latent_dim, hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, max_points * input_dim),
        )

    def _extract_points(self, observation: Any) -> tuple[Tensor, Tensor, bool]:
        if isinstance(observation, Mapping):
            raw_points = observation.get("points", observation.get("positions"))
            raw_mask = observation.get("mask")
        else:
            raw_points = observation
            raw_mask = None

        if raw_points is None:
            raise KeyError("Latent observation must include 'points' or 'positions'.")

        points = _ensure_tensor(raw_points, name="points", device=self.device)
        is_batched = points.ndim == 3
        if points.ndim == 2:
            points = points.unsqueeze(0)
        elif points.ndim != 3:
            raise ValueError("Point clouds must have shape (N, D) or (B, N, D).")
        if points.shape[-1] != self.input_dim:
            raise ValueError(
                f"Expected point dimension {self.input_dim}, got {points.shape[-1]}."
            )
        if points.shape[1] > self.max_points:
            raise ValueError(
                f"Point cloud has {points.shape[1]} points, exceeding max_points={self.max_points}."
            )

        if raw_mask is None:
            mask = torch.ones(points.shape[:2], dtype=torch.bool, device=points.device)
        else:
            mask = _ensure_tensor(raw_mask, name="mask", device=points.device).bool()
            if mask.ndim == 1:
                mask = mask.unsqueeze(0)
            if mask.shape != points.shape[:2]:
                raise ValueError("mask must match point cloud batch and point dimensions.")
        return points, mask, is_batched

    @property
    def device(self) -> torch.device:
        return next(self.parameters()).device

    def _pool_points(self, point_features: Tensor, mask: Tensor) -> Tensor:
        mask_f = mask.unsqueeze(-1).to(dtype=point_features.dtype)
        weighted_sum = torch.sum(point_features * mask_f, dim=1)
        counts = torch.clamp(mask_f.sum(dim=1), min=1.0)
        return weighted_sum / counts

    def reparameterize(self, mean: Tensor, logvar: Tensor) -> Tensor:
        """Sample latent vectors using the reparameterization trick."""
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mean + eps * std

    def encode(self, observation: Any) -> LatentState:
        """Encode a point cloud observation into a latent state."""
        if isinstance(observation, LatentState):
            return observation

        points, mask, is_batched = self._extract_points(observation)
        point_features = self.point_encoder(points)
        pooled = self._pool_points(point_features, mask)
        mean = self.mean_head(pooled)
        logvar = self.logvar_head(pooled)
        latent = self.reparameterize(mean, logvar) if self.training else mean
        num_points = tuple(int(value) for value in mask.sum(dim=1).tolist())
        return LatentState(
            latent=latent,
            mean=mean,
            logvar=logvar,
            num_points=num_points,
            input_dim=self.input_dim,
            batched=is_batched,
            mask=mask,
        )

    def decode(self, state: LatentState | Tensor | np.ndarray) -> dict[str, Any]:
        """Decode a latent state back into a point-cloud observation."""
        if isinstance(state, LatentState):
            latent_state = state
        else:
            latent = _ensure_tensor(state, name="latent", device=self.device)
            if latent.ndim == 1:
                latent = latent.unsqueeze(0)
            if latent.ndim != 2 or latent.shape[1] != self.latent_dim:
                raise ValueError(
                    f"latent must have shape (B, {self.latent_dim}), got {tuple(latent.shape)}."
                )
            zeros = torch.zeros_like(latent)
            latent_state = LatentState(
                latent=latent,
                mean=zeros,
                logvar=zeros,
                num_points=tuple([self.max_points] * latent.shape[0]),
                input_dim=self.input_dim,
                batched=latent.shape[0] > 1,
            )

        decoded = self.decoder(latent_state.latent)
        decoded = decoded.view(-1, self.max_points, self.input_dim)
        counts = latent_state.num_points
        reconstructions = [decoded[i, : count].clone() for i, count in enumerate(counts)]

        if len(reconstructions) == 1 and not latent_state.batched:
            points: Tensor | list[Tensor] = reconstructions[0]
        elif len(set(counts)) == 1:
            points = torch.stack(reconstructions, dim=0)
        else:
            points = reconstructions
        return {"points": points}

    def forward(self, observation: Any) -> tuple[dict[str, Any], LatentState]:
        """Run a full VAE forward pass."""
        state = self.encode(observation)
        reconstruction = self.decode(state)
        return reconstruction, state

    def loss_function(
        self,
        reconstruction: Tensor,
        target: Tensor,
        mean: Tensor,
        logvar: Tensor,
        *,
        mask: Tensor | None = None,
    ) -> Tensor:
        """Compute the beta-VAE objective."""
        target = target.to(reconstruction.device, dtype=reconstruction.dtype)
        if mask is None:
            reconstruction_loss = F.mse_loss(reconstruction, target)
        else:
            mask_f = mask.unsqueeze(-1).to(dtype=reconstruction.dtype)
            squared_error = (reconstruction - target) ** 2
            reconstruction_loss = squared_error.mul(mask_f).sum() / torch.clamp(
                mask_f.sum(), min=1.0
            )
        kl_divergence = -0.5 * torch.mean(
            1 + logvar - mean.pow(2) - logvar.exp()
        )
        return reconstruction_loss + self.beta * kl_divergence

    def get_feature_dim(self) -> int:
        """Return the latent dimensionality."""
        return self.latent_dim

    def __repr__(self) -> str:
        return (
            "LatentRepresentation("
            f"input_dim={self.input_dim}, "
            f"latent_dim={self.latent_dim}, "
            f"hidden_dim={self.hidden_dim}, "
            f"max_points={self.max_points}, "
            f"beta={self.beta})"
        )
