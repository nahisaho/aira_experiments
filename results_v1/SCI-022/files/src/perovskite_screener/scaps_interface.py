"""
Module 5: SCAPS-1D Device Simulation Interface
===============================================
Implements:
  - Parameter file generation for SCAPS-1D (Solar Cell Capacitance Simulator)
  - Material parameter extraction from band gap, defect, and structural data
  - J-V curve simulation via simplified drift-diffusion (1D)
  - Voc, Jsc, FF, PCE extraction
  - Layer stack: FTO/TiO2(ETL)/Perovskite/Spiro(HTL)/Au
  - Python-native fallback simulation when SCAPS binary is unavailable
"""

import numpy as np
from dataclasses import dataclass, field
from typing import Optional, Dict, List
import os


# ── Constants ─────────────────────────────────────────────────────────────────
kB   = 8.617e-5   # eV/K
T    = 300        # K
q    = 1.602e-19  # C
ni_300 = 1e10     # cm⁻³ (reference intrinsic carrier density)


# ── Material Parameters ───────────────────────────────────────────────────────

@dataclass
class LayerParams:
    name: str
    thickness_nm: float
    Eg_eV: float
    chi_eV: float          # electron affinity
    eps_r: float           # relative permittivity
    mu_n: float            # electron mobility (cm²/Vs)
    mu_p: float            # hole mobility (cm²/Vs)
    Nd: float              # donor density (cm⁻³)
    Na: float              # acceptor density (cm⁻³)
    Nt: float              # trap density (cm⁻³)
    Et_eV: float           # trap energy from midgap (eV)
    vth_n: float = 1e7     # thermal velocity (cm/s)
    vth_p: float = 1e7


@dataclass
class DeviceResult:
    formula: str
    Voc_V: float
    Jsc_mAcm2: float
    FF: float
    PCE_percent: float
    Vmp_V: float
    Jmp_mAcm2: float
    Rsh_Ohmcm2: float
    Rs_Ohmcm2: float
    J0_mAcm2: float
    ideality_n: float
    EQE_peak: float
    notes: str = ""


def get_perovskite_layer_params(
    Eg: float,
    B_site: str,
    X_site: str,
    defect_conc: float = 1e15,
    thickness_nm: float = 500,
) -> LayerParams:
    """
    Build LayerParams for ABX3 perovskite absorber.
    Parameters from literature + empirical correlations.
    """
    # Electron affinity correlations (eV): Sn < Pb ≈ Ge < Bi
    chi_map = {"Sn": 3.9, "Ge": 3.8, "Bi": 3.6, "Pb": 3.93}
    chi = chi_map.get(B_site, 3.9) + (1.4 - Eg) * 0.15  # tuned to halide

    # Permittivity
    eps_map = {"Sn": 20.0, "Ge": 18.0, "Bi": 22.0, "Pb": 24.0}
    eps_r = eps_map.get(B_site, 20.0)

    # Mobilities (cm²/Vs) — Sn highest, Bi lowest
    mob_map = {
        "Sn":  {"n": 320,  "p": 280},
        "Ge":  {"n": 180,  "p": 150},
        "Bi":  {"n":  40,  "p":  25},
        "Pb":  {"n": 200,  "p": 160},
    }
    mobs = mob_map.get(B_site, {"n": 100, "p": 80})

    # Trap energy at midgap
    Et = Eg / 2 * 0.95  # near midgap

    return LayerParams(
        name=f"{B_site}{X_site}3_absorber",
        thickness_nm=thickness_nm,
        Eg_eV=Eg,
        chi_eV=round(chi, 3),
        eps_r=eps_r,
        mu_n=mobs["n"],
        mu_p=mobs["p"],
        Nd=1e14,
        Na=1e13,
        Nt=defect_conc,
        Et_eV=round(Et, 3),
    )


