# ── Python-Native Drift-Diffusion Simulation ─────────────────────────────────

def simulate_jv_curve(
    absorber: LayerParams,
    formula: str,
    illumination: float = 100.0,
    T_K: float = 300.0,
    n_points: int = 141,
) -> DeviceResult:
    """
    Python-native 1D drift-diffusion J-V simulation.
    Implements simplified two-diode model with SRH recombination.
    """
    kT_eV = kB * T_K
    Eg    = absorber.Eg_eV
    L_cm  = absorber.thickness_nm * 1e-7

    # ── Photocurrent density (Jph) ────────────────────────────────────────
    # Integrate AM1.5G flux above Eg
    E_arr  = np.linspace(0.3, 4.5, 2000)
    flux   = 3.3e21 * E_arr**2 * np.exp(-E_arr / (kT_eV * 30))  # proxy AM1.5G
    flux   /= np.trapezoid(flux, E_arr) / 4.2e17   # normalize

    alpha_above = 1.5e5 * np.sqrt(np.maximum(E_arr - Eg, 0))
    absorptance = 1 - np.exp(-2 * alpha_above * L_cm)
    Jph = q * np.trapezoid(flux * absorptance, E_arr) * 1e3  # mA/cm²
    Jph = min(Jph * illumination / 100, 30.0)

    # ── Recombination parameters ──────────────────────────────────────────
    # SRH lifetime from trap density
    sigma_n = 1e-14  # cm²
    vth     = 1e7    # cm/s
    tau_SRH = 1 / (sigma_n * vth * absorber.Nt + 1e-30)
    tau_SRH = np.clip(tau_SRH, 1e-9, 1e-5)

    # Radiative recombination B coefficient
    B_rad = 1e-10  # cm³/s (direct-gap perovskite)

    # Minority carrier lifetime (effective)
    ni   = ni_300 * np.exp(-(Eg - 1.12) / (2 * kT_eV))
    ni   = max(ni, 1e1)
    tau_eff = tau_SRH / (1 + B_rad * ni / (sigma_n * vth * absorber.Nt + 1e-30))
    tau_eff = np.clip(tau_eff, 1e-9, 1e-4)

    # Diffusion lengths
    Dp    = kT_eV * absorber.mu_p
    Dn    = kT_eV * absorber.mu_n
    Lp    = np.sqrt(Dp * tau_eff)
    Ln    = np.sqrt(Dn * tau_eff)
    L_eff = (Lp + Ln) / 2

    # ── Dark saturation current J0 ────────────────────────────────────────
    J0_rad = q * B_rad * ni**2 * L_cm  # radiative recombination
    J0_SRH = q * ni * L_cm / (2 * tau_SRH + 1e-30)  # SRH midgap
    J0     = J0_rad + J0_SRH
    J0_mA  = J0 * 1e3

    # ── Two-diode J-V model ───────────────────────────────────────────────
    V_arr   = np.linspace(0, Eg * 1.05, n_points)
    n1, n2  = 1.0, 2.0  # ideality factors
    Rs      = 2.5        # Ohm·cm²
    Rsh     = 1000       # Ohm·cm² (shunt resistance)

    # Iterative solution for implicit J
    J_arr = np.zeros(n_points)
    J_cur = Jph
    for i, V in enumerate(V_arr):
        for _ in range(20):  # Newton iteration
            J1   = J0_mA * (np.exp(q * (V - J_cur * Rs * 1e-3) / (n1 * kB * T_K * q / q)) - 1)
            J2   = J0_mA * (np.exp(q * (V - J_cur * Rs * 1e-3) / (n2 * kB * T_K * q / q)) - 1)
            Jsh  = (V - J_cur * Rs * 1e-3) / Rsh * 1e3
            J_new = Jph - J1 - J2 - Jsh
            if abs(J_new - J_cur) < 1e-6:
                break
            J_cur = J_new
        J_arr[i] = max(J_cur, 0)

    # ── Device metrics ────────────────────────────────────────────────────
    P_arr = J_arr * V_arr
    idx_mpp = np.argmax(P_arr)

    Voc_idx = np.argmin(np.abs(J_arr))
    Voc = V_arr[Voc_idx] if Voc_idx > 0 else 0.0
    Voc = min(Voc, Eg * 0.82)

    Jsc   = float(J_arr[0])
    Vmp   = float(V_arr[idx_mpp])
    Jmp   = float(J_arr[idx_mpp])
    Pmax  = Vmp * Jmp
    FF    = Pmax / (Jsc * Voc) if Jsc > 0 and Voc > 0 else 0.0
    FF    = np.clip(FF, 0.3, 0.89)
    PCE   = Pmax / illumination * 100

    # EQE peak (simplified)
    EQE_peak = min(0.95, Jsc / 26.0)

    n_ideal = 1.0 + 0.5 * (absorber.Nt / 1e15) ** 0.2

    note = ""
    if absorber.Nt > 1e17:
        note = "High trap density; PCE limited by SRH recombination"

    return DeviceResult(
        formula=formula, Voc_V=round(Voc, 4),
        Jsc_mAcm2=round(Jsc, 3), FF=round(FF, 4),
        PCE_percent=round(PCE, 2),
        Vmp_V=round(Vmp, 4), Jmp_mAcm2=round(Jmp, 3),
        Rsh_Ohmcm2=Rsh, Rs_Ohmcm2=Rs,
        J0_mAcm2=round(J0_mA, 6),
        ideality_n=round(n_ideal, 3),
        EQE_peak=round(EQE_peak, 3),
        notes=note,
    )


def run_scaps_simulation(
    A: str, B: str, X: str, Eg: float,
    defect_conc: float = 1e15,
    thickness_nm: float = 500,
    output_dir: str = "results/scaps",
) -> DeviceResult:
    """
    High-level entry: build SCAPS file + run Python simulation.
    """
    formula  = f"{A}{B}{X}3"
    absorber = get_perovskite_layer_params(Eg, B, X, defect_conc, thickness_nm)
    scaps_file = build_scaps_input(absorber, formula, output_dir=output_dir)
    result     = simulate_jv_curve(absorber, formula)
    return result
